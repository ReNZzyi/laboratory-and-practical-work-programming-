# 1. Переменная — это имя, которое ссылается на объект в памяти. При записи `x = 5` создаётся объект `5`, и имя `x` связывается с ним. Корректные имена: `count`, `user_name`, `_total2`. Некорректное: `2price`, так как имя не может начинаться с цифры.

# 2. `int` (`42` → `<class 'int'>`), `float` (`3.14` → `<class 'float'>`), `str` (`"hi"` → `<class 'str'>`), `bool` (`True` → `<class 'bool'>`), `NoneType` (`None` → `<class 'NoneType'>`). Типизация динамическая: тип определяется во время выполнения и принадлежит объекту, а не переменной, поэтому одной переменной можно присвоить сначала число, а потом строку.

# 3. `print()` выводит значения в консоль.
#    - `print(x)` → `10`
#    - `print("x =", x)` → `x = 10`
#    - `print(f"Значение: {x}")` → `Значение: 10`

#    При перечислении через запятую пробелы между значениями ставятся автоматически. f‑строка — это одна готовая строка, её формат задаётся вручную.

# 4. `type()` возвращает тип объекта: `type(7)` → `<class 'int'>`, `type("7")` → `<class 'str'>`, `type(True)` → `<class 'bool'>`. Запись `<class 'int'>` означает, что объект является экземпляром класса `int`.

# 5. Примеры операций:
#    - `5 + 2.0` → `7.0` (float)
#    - `5 - 2` → `3` (int)
#    - `3 * 2.5` → `7.5` (float)
#    - `6 / 2` → `3.0` (деление `/` всегда даёт float)
#    - `7 // 2` → `3` (int)
#    - `7 % 3` → `1` (int)
#    - `2 ** 3` → `8` (int)

#    Если в операции есть float, результат тоже будет float.

# 6. `/` даёт точный результат типа float, а `//` округляет результат вниз (к −∞).
#    - `7 / 2` → `3.5`, `7 // 2` → `3`
#    - `9 / 4` → `2.25`, `9 // 4` → `2`
#    - `-7 / 2` → `-3.5`, `-7 // 2` → `-4`
#    - `7 / -2` → `-3.5`, `7 // -2` → `-4`

# 7. Примеры преобразований: `int("42")` → `42`, `int(3.9)` → `3`, `float("2.5")` → `2.5`, `str(100)` → `'100'`. Ошибка возникает, если строку нельзя прочитать как число: `int("abc")` и `int("3.5")` вызывают `ValueError`.

# 8. Выражение вычисляется в значение, которое можно сохранить в переменную или передать в функцию:
#    - `s = 2 + 3 * 4` → `14`
#    - `b = 10 > 3` → `True`
#    - `l = True and False` → `False`
#    - `print(5 != 5)` → `False`

# 9. Сравнения возвращают `bool`.
#    - `5 > 3 and 2 == 2` → `True`
#    - `not 1 > 2 or 3 < 1` → `True`
#    - `1 < 3 < 5` → `True`

#    Порядок вычисления: арифметика → сравнения → `not` → `and` → `or`. Операторы `and` и `or` вычисляются лениво: правая часть не вычисляется, если результат уже ясен по левой.

# 10. Неявное приведение выполняется только между числами (`bool → int → float`): `3 + 2.5` → `5.5`, `True + 1` → `2`. Строки и числа автоматически не приводятся: `"5" + 3` → `TypeError`. Нужно явное преобразование: `"5" + str(3)` → `'53'`, `int("5") + 3` → `8`.

# 11. Способы вывода:
#     - `print(name, age)` — быстро, удобно для отладки.
#     - `print(f"{name}: {age}")` — самый читаемый вариант.
#     - `print("{}: {}".format(name, age))` — удобно, когда шаблон хранится отдельно.
#     - `print(name + ": " + str(age))` — работает только со строками.

# 12. Порядок операций: `()` → `**` → унарный `-` → `* / // %` → `+ -` → сравнения → `not` → `and` → `or`. Пример: в `2 + 3 * 4 ** 2` сначала `4**2=16`, затем `3*16=48`, затем `2+48=50`. Скобки меняют порядок: `(2 + 3) * 4 ** 2` → `5*16=80`.

# 13. Примеры:
#     - `a, b, c = 1, 2, 3` — присваивание нескольким переменным сразу
#     - `x = y = 0` — одно значение нескольким переменным
#     - `a, b = b, a` — обмен значений без временной переменной
#     - `p, q = (10, 20)` — распаковка кортежа
#     - `first, *rest = [1, 2, 3, 4]` — распаковка списка (`first=1`, `rest=[2, 3, 4]`)

# 14. Неизменяемые типы: `int`, `float`, `str`, `bool`, `tuple`. Изменяемые: `list`, `dict`, `set`. Если `s = "abc"`, то после `s = s + "d"` значение `id(s)` будет другим, то есть создан новый объект. Попытка `s[0] = "z"` вызывает `TypeError`.

# 15. Пример:
n = 10                       # int
f = 2.5                      # float
text = "Итог"                # str
res = n * f                  # 25.0, float (int * float → float)
ok = res > 20                # True, bool (результат сравнения)
print(text, res, ok)         # Итог 25.0 True
print(type(res), type(ok))   # <class 'float'> <class 'bool'>